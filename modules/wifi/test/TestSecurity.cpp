#include <array>
#include <cstdint>

#include <gtest/gtest.h>

#include <sihd/util/Logger.hpp>
#include <sihd/wifi/scan.hpp>

namespace test
{
using namespace sihd::util;
using namespace sihd::wifi;

class TestSecurity: public ::testing::Test
{
    protected:
        TestSecurity() { LoggerManager::stream(); }

        virtual ~TestSecurity() { LoggerManager::clear_loggers(); }

        template <size_t N>
        static Security security(const std::array<uint8_t, N> & elements, bool privacy)
        {
            return security_of(ArrUByteView(elements.data(), elements.size()), privacy);
        }
};

TEST_F(TestSecurity, test_security_without_rsn)
{
    const std::array<uint8_t, 6> ssid_only = {0x00, 0x04, 'h', 'o', 'm', 'e'};

    EXPECT_EQ(security_of(ArrUByteView(), false), Security::open);
    EXPECT_EQ(security(ssid_only, false), Security::open);
    EXPECT_EQ(security(ssid_only, true), Security::wep);
}

TEST_F(TestSecurity, test_security_rsn_personal)
{
    const std::array<uint8_t, 22> psk = {0x30, 0x14, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x04, 0x01, 0x00, 0x00,
                                         0x0f, 0xac, 0x04, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x02, 0x00, 0x00};
    const std::array<uint8_t, 22> sae = {0x30, 0x14, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x04, 0x01, 0x00, 0x00,
                                         0x0f, 0xac, 0x04, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x08, 0xc0, 0x00};

    EXPECT_EQ(security(psk, true), Security::personal);
    EXPECT_EQ(security(sae, true), Security::personal);
}

TEST_F(TestSecurity, test_security_rsn_transition)
{
    const std::array<uint8_t, 32> ssid_then_psk_and_sae = {
        0x00, 0x04, 'h',  'o',  'm',  'e',  0x30, 0x18, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x04, 0x01, 0x00,
        0x00, 0x0f, 0xac, 0x04, 0x02, 0x00, 0x00, 0x0f, 0xac, 0x02, 0x00, 0x0f, 0xac, 0x08, 0x80, 0x00};

    EXPECT_EQ(security(ssid_then_psk_and_sae, true), Security::personal);
}

TEST_F(TestSecurity, test_security_rsn_enterprise_and_owe)
{
    const std::array<uint8_t, 22> ieee8021x = {0x30, 0x14, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x04, 0x01, 0x00, 0x00,
                                               0x0f, 0xac, 0x04, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x01, 0x00, 0x00};
    const std::array<uint8_t, 22> owe = {0x30, 0x14, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x04, 0x01, 0x00, 0x00,
                                         0x0f, 0xac, 0x04, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x12, 0xc0, 0x00};

    EXPECT_EQ(security(ieee8021x, true), Security::enterprise);
    EXPECT_EQ(security(owe, true), Security::owe);
}

TEST_F(TestSecurity, test_security_wpa_vendor_element)
{
    const std::array<uint8_t, 24> wpa_psk = {0xdd, 0x16, 0x00, 0x50, 0xf2, 0x01, 0x01, 0x00, 0x00, 0x50, 0xf2, 0x02,
                                             0x01, 0x00, 0x00, 0x50, 0xf2, 0x02, 0x01, 0x00, 0x00, 0x50, 0xf2, 0x02};
    const std::array<uint8_t, 24> wpa_eap = {0xdd, 0x16, 0x00, 0x50, 0xf2, 0x01, 0x01, 0x00, 0x00, 0x50, 0xf2, 0x02,
                                             0x01, 0x00, 0x00, 0x50, 0xf2, 0x02, 0x01, 0x00, 0x00, 0x50, 0xf2, 0x01};
    const std::array<uint8_t, 9> other_vendor = {0xdd, 0x07, 0x00, 0x50, 0xf2, 0x04, 0x10, 0x4a, 0x00};

    EXPECT_EQ(security(wpa_psk, true), Security::personal);
    EXPECT_EQ(security(wpa_eap, true), Security::enterprise);
    EXPECT_EQ(security(other_vendor, true), Security::wep);
}

TEST_F(TestSecurity, test_security_rsn_wins_over_wpa)
{
    const std::array<uint8_t, 46> wpa_eap_then_rsn_psk = {
        0xdd, 0x16, 0x00, 0x50, 0xf2, 0x01, 0x01, 0x00, 0x00, 0x50, 0xf2, 0x02, 0x01, 0x00, 0x00, 0x50,
        0xf2, 0x02, 0x01, 0x00, 0x00, 0x50, 0xf2, 0x01, 0x30, 0x14, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x04,
        0x01, 0x00, 0x00, 0x0f, 0xac, 0x04, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x02, 0x00, 0x00};

    EXPECT_EQ(security(wpa_eap_then_rsn_psk, true), Security::personal);
}

TEST_F(TestSecurity, test_security_truncated)
{
    const std::array<uint8_t, 4> element_past_the_end = {0x30, 0x14, 0x01, 0x00};
    const std::array<uint8_t, 10> rsn_without_akms = {0x30, 0x08, 0x01, 0x00, 0x00, 0x0f, 0xac, 0x04, 0x01, 0x00};
    const std::array<uint8_t, 1> lone_id = {0x30};

    EXPECT_EQ(security(element_past_the_end, true), Security::unknown);
    EXPECT_EQ(security(rsn_without_akms, true), Security::unknown);
    EXPECT_EQ(security(lone_id, false), Security::unknown);
}

} // namespace test
